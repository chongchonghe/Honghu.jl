# Reference solutions used to verify the solvers: the exact Riemann problem for
# the 1D Euler equations (Toro 2009, chapter 4), and the semi-analytic radiative
# shock of Lowrie & Edwards (2008) read from a vendored table.

const _LE_SHOCK_FILE = joinpath(@__DIR__, "data", "lowrie_edwards_shock.txt")

"""
    radhydro_shock_exact() -> (x, rho, v, Tmat, Trad)

Semi-analytic solution of the Mach 3 radiative shock of Lowrie & Edwards (2008),
in the dimensionless units of [`radhydro_shock`](@ref).

Columns are position, density, velocity, matter temperature and radiation
temperature, all as `Vector{Float64}` sorted by `x`. The table is a subsample of
the one shipped with Quokka, generated by `extern/LowrieEdwards/radshock.py`,
kept at full resolution across the Zel'dovich spike.

The solution is derived under the Eddington (P1) approximation, which is why
`radhydro_shock` runs with [`EddingtonClosure`](@ref).
"""
function radhydro_shock_exact()
    x = Float64[]
    rho = Float64[]
    v = Float64[]
    tmat = Float64[]
    trad = Float64[]
    for line in eachline(_LE_SHOCK_FILE)
        (isempty(line) || startswith(line, '#')) && continue
        f = split(line)
        push!(x, parse(Float64, f[1]))
        push!(rho, parse(Float64, f[2]))
        push!(v, parse(Float64, f[3]))
        push!(tmat, parse(Float64, f[4]))
        push!(trad, parse(Float64, f[5]))
    end
    return x, rho, v, tmat, trad
end

"""
    interpolate_to(xq, x, y) -> Vector

Linear interpolation of the samples `(x, y)`, which must be sorted by `x`, onto
the query points `xq`. Values outside the range of `x` are clamped to the end
points.
"""
function interpolate_to(xq::AbstractVector, x::AbstractVector, y::AbstractVector)
    out = similar(collect(float.(xq)))
    for (m, xm) in enumerate(xq)
        if xm <= first(x)
            out[m] = first(y)
        elseif xm >= last(x)
            out[m] = last(y)
        else
            i = searchsortedlast(x, xm)
            t = (xm - x[i]) / (x[i+1] - x[i])
            out[m] = (1 - t) * y[i] + t * y[i+1]
        end
    end
    return out
end

# --- exact Riemann solver ---------------------------------------------------

"""
    sod_exact(x, t; rhoL = 1.0, uL = 0.0, pL = 1.0,
                    rhoR = 0.125, uR = 0.0, pR = 0.1,
                    gamma = 1.4, x0 = 0.5) -> (rho, u, p)

Exact solution of the Riemann problem with the given left and right states,
sampled at position `x` and time `t`. The defaults are the standard Sod shock
tube.

The star pressure is found by Newton iteration on the pressure function, then
the solution is sampled along the ray `S = (x - x0)/t`.
"""
function sod_exact(x::Real, t::Real; rhoL=1.0, uL=0.0, pL=1.0,
                   rhoR=0.125, uR=0.0, pR=0.1, gamma=1.4, x0=0.5)
    g = float(gamma)
    t <= 0 && return x < x0 ? (rhoL, uL, pL) : (rhoR, uR, pR)
    cL = sqrt(g * pL / rhoL)
    cR = sqrt(g * pR / rhoR)
    pstar, ustar = _star_state(rhoL, uL, pL, cL, rhoR, uR, pR, cR, g)
    return _sample((x - x0) / t, pstar, ustar, rhoL, uL, pL, cL, rhoR, uR, pR, cR, g)
end

# pressure function and its derivative for one side
function _pfunc(p, rhoK, pK, cK, g)
    if p > pK   # shock
        A = 2 / ((g + 1) * rhoK)
        B = (g - 1) / (g + 1) * pK
        s = sqrt(A / (B + p))
        return (p - pK) * s, s * (1 - (p - pK) / (2 * (B + p)))
    else        # rarefaction
        pr = p / pK
        return (2 * cK / (g - 1)) * (pr^((g - 1) / (2g)) - 1), pr^(-(g + 1) / (2g)) / (rhoK * cK)
    end
end

function _star_state(rhoL, uL, pL, cL, rhoR, uR, pR, cR, g)
    du = uR - uL
    # two-rarefaction approximation as the initial guess
    p = ((cL + cR - (g - 1) / 2 * du) / (cL / pL^((g - 1) / (2g)) + cR / pR^((g - 1) / (2g))))^(2g / (g - 1))
    p = max(p, 1e-12)
    for _ in 1:100
        fL, dfL = _pfunc(p, rhoL, pL, cL, g)
        fR, dfR = _pfunc(p, rhoR, pR, cR, g)
        f = fL + fR + du
        dp = f / (dfL + dfR)
        pnew = max(p - dp, 1e-12)
        abs(pnew - p) <= 1e-14 * (abs(pnew) + abs(p)) && (p = pnew; break)
        p = pnew
    end
    fL, _ = _pfunc(p, rhoL, pL, cL, g)
    fR, _ = _pfunc(p, rhoR, pR, cR, g)
    return p, (uL + uR + fR - fL) / 2
end

function _sample(S, pstar, ustar, rhoL, uL, pL, cL, rhoR, uR, pR, cR, g)
    if S <= ustar
        # left of the contact
        if pstar > pL   # left shock
            SL = uL - cL * sqrt((g + 1) / (2g) * pstar / pL + (g - 1) / (2g))
            S <= SL && return (rhoL, uL, pL)
            r = pstar / pL
            rho = rhoL * (r + (g - 1) / (g + 1)) / ((g - 1) / (g + 1) * r + 1)
            return (rho, ustar, pstar)
        else            # left rarefaction
            SH = uL - cL
            S <= SH && return (rhoL, uL, pL)
            cstar = cL * (pstar / pL)^((g - 1) / (2g))
            ST = ustar - cstar
            if S >= ST
                return (rhoL * (pstar / pL)^(1 / g), ustar, pstar)
            end
            # inside the fan
            u = 2 / (g + 1) * (cL + (g - 1) / 2 * uL + S)
            c = 2 / (g + 1) * (cL + (g - 1) / 2 * (uL - S))
            rho = rhoL * (c / cL)^(2 / (g - 1))
            return (rho, u, pL * (c / cL)^(2g / (g - 1)))
        end
    else
        # right of the contact
        if pstar > pR   # right shock
            SR = uR + cR * sqrt((g + 1) / (2g) * pstar / pR + (g - 1) / (2g))
            S >= SR && return (rhoR, uR, pR)
            r = pstar / pR
            rho = rhoR * (r + (g - 1) / (g + 1)) / ((g - 1) / (g + 1) * r + 1)
            return (rho, ustar, pstar)
        else            # right rarefaction
            SH = uR + cR
            S >= SH && return (rhoR, uR, pR)
            cstar = cR * (pstar / pR)^((g - 1) / (2g))
            ST = ustar + cstar
            if S <= ST
                return (rhoR * (pstar / pR)^(1 / g), ustar, pstar)
            end
            u = 2 / (g + 1) * (-cR + (g - 1) / 2 * uR + S)
            c = 2 / (g + 1) * (cR - (g - 1) / 2 * (uR - S))
            rho = rhoR * (c / cR)^(2 / (g - 1))
            return (rho, u, pR * (c / cR)^(2g / (g - 1)))
        end
    end
end
